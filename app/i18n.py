def t(key: str, lang: str = "ar", **params: Any) -> str:
    pair = S.get(key)
    if pair is None:
        return key
    text = pair[0] if lang == "ar" else pair[1]
    if params:
        resolved = {k: resolve(v, lang) for k, v in params.items()}
        try:
            text = text.format(**resolved)
        except (KeyError, IndexError, ValueError):
            pass
    return text


def resolve(v: Any, lang: str) -> str:
    """Turn a parameter (str, {ar,en} dict, list) into display text."""
    if v is None:
        return ""
    if isinstance(v, dict) and ("ar" in v or "en" in v):
        return v.get(lang) or v.get("ar") or ""
    if isinstance(v, (list, tuple)):
        sep = "، " if lang == "ar" else ", "
        return sep.join(resolve(x, lang) for x in v)
    return str(v)
